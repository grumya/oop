package sort;

/**
 * Цвета вершин, используемые в алгоритме поиска в глубину (DFS)
 * при проверке графа на наличие циклов.
 */
public enum DfsColors {
    WHITE, // Вершина еще не посещена
    GREY,  // Вершина обрабатывается в текущей ветке рекурсии (признак цикла)
    BLACK  // Вершина и все ее потомки полностью обработаны
}